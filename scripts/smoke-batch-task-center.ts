import { app, BrowserWindow, session } from 'electron';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve(process.env.TASK_CENTER_SMOKE_ROOT!);
app.setPath('userData', join(root, 'profile'));
app.disableHardwareAcceleration();
app.on('window-all-closed', () => {});
const sleep = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));
async function run() {
  await app.whenReady();
  const browser = session.fromPartition('task-center-fixture');
  let networkRequests = 0;
  browser.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_request, callback) => { networkRequests++; callback({ cancel: true }); });
  const window = new BrowserWindow({ width: 1024, height: 800, show: false, webPreferences: { session: browser, sandbox: true, contextIsolation: true, backgroundThrottling: false } });
  await window.loadFile(join(root, 'index.html'));
  const evaluate = <T = unknown>(expression: string): Promise<T> => window.webContents.executeJavaScript(expression, true);
  const until = async (expression: string) => { for (let i = 0; i < 160; i++) { if (await evaluate(expression)) return; await sleep(25); } throw new Error('UI condition timed out: ' + expression); };
  const click = (text: string) => evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)});if(!b)throw Error('Button missing');b.click()})()`);
  await until('document.querySelectorAll("tbody tr[data-task-id]").length===3');
  assert.deepEqual(await evaluate('window.taskCenterFixture.calls.batch[0]'), ['guangdong-hrss', 'batch-a']);
  assert.equal(await evaluate('window.taskCenterFixture.calls.page.length'), 0);
  assert.equal(await evaluate('document.body.innerText.includes("2026-11-01 至 2026-11-25")'), true);
  const layout = await evaluate<{ columns: number; overflow: boolean; controls: boolean }>(`({columns:getComputedStyle(document.querySelector('.return-batch-counts')).gridTemplateColumns.split(' ').length,overflow:document.documentElement.scrollWidth>innerWidth,controls:[...document.querySelectorAll('button')].every(b=>b.getBoundingClientRect().height>=44)})`);
  assert.equal(layout.columns, 6); assert.equal(layout.overflow, false); assert.equal(layout.controls, true);
  await evaluate('document.querySelector("[data-task-id=done-other] button").click()');
  assert.deepEqual(await evaluate('window.taskCenterFixture.viewed'), { systemId: 'guangdong-hrss', matterId: 'startup-training', taskId: 'done-other' });
  await click('取消等待任务');
  await until('document.querySelector("[data-task-id=waiting] .status-chip").textContent==="已取消"');
  assert.deepEqual(await evaluate('window.taskCenterFixture.calls.pending'), [['guangdong-hrss', 'batch-a']]);
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='取消等待任务').disabled`), true);
  await evaluate('window.taskCenterFixture.holdRetry=true');
  await evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent==='重新回流失败项');b.click();b.click()})()`);
  await until('window.taskCenterFixture.calls.retry.length===1');
  await evaluate('window.taskCenterFixture.resolveRetry()');
  await until('Boolean(document.querySelector("[data-task-id=retry-task]"))');
  assert.deepEqual(await evaluate('window.taskCenterFixture.calls.retry'), [['guangdong-hrss', 'batch-a']]);
  await click('返回当前事项任务');
  await until('Boolean(document.querySelector("[data-task-id=single-task]"))');
  assert.deepEqual(await evaluate('window.taskCenterFixture.calls.page.at(-1)'), { systemId: 'guangdong-hrss', matterId: 'unemployment', page: 1, pageSize: 50 });
  await evaluate('document.querySelector(".task-parent-batch").click()');
  await until('Boolean(document.querySelector("[data-task-id=failed]"))');
  await evaluate('window.taskCenterFixture.chooseBatch("batch-late")');
  await until('window.taskCenterFixture.calls.batch.some(c=>c[1]==="batch-late")');
  await click('返回当前事项任务');
  await until('Boolean(document.querySelector("[data-task-id=single-task]"))');
  await evaluate('window.taskCenterFixture.resolveLate()');
  await sleep(100);
  assert.equal(await evaluate('Boolean(document.querySelector("[data-task-id=must-not-render-late]"))'), false);
  await evaluate('document.querySelector("[data-task-id=single-task] .error-text").click()');
  await until('document.querySelector("[data-task-id=single-task] .status-chip").textContent==="已取消"');
  assert.deepEqual(await evaluate('window.taskCenterFixture.calls.cancel'), ['single-task']);
  await evaluate('window.taskCenterFixture.failNext=true;window.taskCenterFixture.chooseBatch("batch-error")');
  await until('document.querySelector(".inline-error")?.textContent.includes("合成批次读取失败")');
  await click('重新加载');
  await until('Boolean(document.querySelector("[data-task-id=retry-task]"))');
  await evaluate('window.taskCenterFixture.chooseBatch("batch-a")');
  await until('Boolean(document.querySelector("[data-task-id=failed]"))');
  await evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  await sleep(100);
  const screenshot = await window.webContents.capturePage();
  await writeFile(join(root, 'task-center-1024.png'), screenshot.toPNG());
  assert.equal(networkRequests, 0);
  await writeFile(join(root, 'verification.json'), JSON.stringify({ passed: true, networkRequests, layout, covered: ['batch-cross-matter-scope', 'cancel-pending', 'retry-failed', 'double-click-guard', 'view-correct-matter', 'single-history', 'historical-batch-link', 'stale-poll-discard', 'single-cancel', 'reload-after-error'] }, null, 2));
  console.log(JSON.stringify({ passed: true, networkRequests, screenshot: join(root, 'task-center-1024.png') }));
  window.destroy(); app.quit();
}
run().catch(error => { console.error(error); app.exit(1); });
