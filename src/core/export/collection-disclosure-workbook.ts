import ExcelJS from 'exceljs';
import { DOUBLE_PUBLICITY_TEMPLATE } from '../double-publicity/template';
import { exportFieldValue } from '../double-publicity/validation';
import type { StoredRecord } from '../storage/types';

// AdministrativeLicense.java adds the sequence number before the shared 31 permit fields.
const columns = [['orderNo', '序号'], ...DOUBLE_PUBLICITY_TEMPLATE] as const;

const grey = { argb: 'FF808080' };
const edge: Partial<ExcelJS.Border> = { style: 'thin', color: grey };
const dataStyle: Partial<ExcelJS.Style> = {
  font: { name: 'Arial', size: 10 },
  alignment: { horizontal: 'center', vertical: 'middle' },
  border: { top: edge, right: edge, bottom: edge, left: edge },
};
const headerStyle: Partial<ExcelJS.Style> = {
  ...dataStyle,
  font: { ...dataStyle.font, bold: true, color: { argb: 'FFFFFFFF' } },
  fill: { type: 'pattern', pattern: 'solid', fgColor: grey },
};

function disclosureValue(record: StoredRecord, key: string): string {
  const value = exportFieldValue(record, key) ?? record.data[key];
  const text = typeof value === 'string' || typeof value === 'number' ? String(value) : '';
  // AdministrativeLicenseController normalizes only the natural person's document type.
  return key === 'xkXdrZjlx' && text.includes('身份证') ? '身份证' : text;
}

/** Mirrors the collection system's generic administrative-permit ExcelUtil export. */
export function createCollectionDisclosureWorkbook(records: readonly StoredRecord[]): ExcelJS.Workbook {
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('行政许可');
  // Dimensions from a workbook generated by the original ExcelUtil.
  sheet.properties.defaultRowHeight = 13.5;
  sheet.columns = columns.map(([, header]) => ({ header, width: 16.7166666666667 }));
  sheet.getRow(1).eachCell(cell => { cell.style = headerStyle; });
  records.forEach((record, index) => {
    // All original columns use @Excel's default string type, including the sequence number.
    const row = sheet.addRow(columns.map(([key]) =>
      key === 'orderNo' ? String(index + 1) : disclosureValue(record, key)));
    row.height = 14;
    row.eachCell({ includeEmpty: true }, cell => { cell.style = dataStyle; });
  });
  return workbook;
}
